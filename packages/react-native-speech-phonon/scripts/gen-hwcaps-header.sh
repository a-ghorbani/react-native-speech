#!/usr/bin/env bash
# Write phonon_required_hwcaps.h: the HWCAP bits libptts_ffi.so needs on arm64, generated from the
# same ARM64_FEATURES the library was compiled with, so the gate on the phone can never drift from
# the build.
#
# Usage: gen-hwcaps-header.sh <features, e.g. +dotprod,+fp16> <out.h>
#
# The header defines, on aarch64 (all zero elsewhere, so it can be included on x86_64 too):
#   PHONON_ARM64_FEATURES      the feature string, for diagnostics and the lock check
#   PHONON_REQUIRED_HWCAP      mask of AT_HWCAP bits
#   PHONON_REQUIRED_HWCAP2     mask of AT_HWCAP2 bits
#   PHONON_REQUIRED_HWCAP_LIST(X)  X(word, bit, "name") per required bit, to name missing ones
set -euo pipefail
if ((BASH_VERSINFO[0] < 4)); then
  echo "gen-hwcaps-header.sh needs bash >= 4" >&2
  exit 2
fi

HERE="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=arm64-features.sh
source "$HERE/arm64-features.sh"

if [[ $# -ne 2 ]]; then
  echo "usage: $0 <arm64 features> <out.h>" >&2
  exit 2
fi
FEATURES="$1"
OUT="$2"

names="$(phonon_parse_features "$FEATURES")"

hwcap=() hwcap2=() list=()
for name in $names; do
  for pair in ${PHONON_FEATURE_HWCAPS[$name]}; do
    word="${pair%%:*}"
    macro="${pair#*:}"
    if [[ "$word" == 1 ]]; then hwcap+=("$macro"); else hwcap2+=("$macro"); fi
    # The name as /proc/cpuinfo prints it: HWCAP_ASIMDDP -> asimddp.
    pretty="$(echo "${macro#HWCAP*_}" | tr '[:upper:]' '[:lower:]')"
    list+=("  X($word, $macro, \"$pretty\")")
  done
done

join_or_zero() {
  if [[ $# -eq 0 ]]; then echo "0"; else local IFS='|'; echo "($*)" | sed 's/|/ | /g'; fi
}

mkdir -p "$(dirname "$OUT")"
{
  echo "// Generated by scripts/gen-hwcaps-header.sh from ARM64_FEATURES=\"$FEATURES\"."
  echo "// Do not edit: it must match the features libptts_ffi.so was compiled with."
  echo "#ifndef PHONON_REQUIRED_HWCAPS_H"
  echo "#define PHONON_REQUIRED_HWCAPS_H"
  echo ""
  echo "#define PHONON_ARM64_FEATURES \"$FEATURES\""
  echo ""
  echo "#if defined(__aarch64__)"
  echo "#include <asm/hwcap.h>"
  echo "#define PHONON_REQUIRED_HWCAP $(join_or_zero "${hwcap[@]+"${hwcap[@]}"}")"
  echo "#define PHONON_REQUIRED_HWCAP2 $(join_or_zero "${hwcap2[@]+"${hwcap2[@]}"}")"
  if [[ ${#list[@]} -eq 0 ]]; then
    echo "#define PHONON_REQUIRED_HWCAP_LIST(X)"
  else
    echo "#define PHONON_REQUIRED_HWCAP_LIST(X) \\"
    for ((i = 0; i < ${#list[@]}; i++)); do
      if ((i + 1 < ${#list[@]})); then echo "${list[$i]} \\"; else echo "${list[$i]}"; fi
    done
  fi
  echo "#else"
  echo "#define PHONON_REQUIRED_HWCAP 0"
  echo "#define PHONON_REQUIRED_HWCAP2 0"
  echo "#define PHONON_REQUIRED_HWCAP_LIST(X)"
  echo "#endif"
  echo ""
  echo "#endif"
} >"$OUT"
